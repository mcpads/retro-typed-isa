#[test]
fn every_manual_vfpu_encoding_decodes_and_reencodes_exactly() {
    assert_eq!(MANUAL_VFPU_FORMS.len(), 268);

    for &(mnemonic, word) in MANUAL_VFPU_FORMS {
        let instruction = decode_word(word, ADDRESS)
            .unwrap_or_else(|error| panic!("{mnemonic} {word:#010x}: {error}"));
        let Instruction::Vfpu(vfpu) = &instruction else {
            panic!("{mnemonic} {word:#010x} decoded outside the VFPU profile");
        };
        assert_eq!(vfpu.form().mnemonic(), mnemonic);
        assert_eq!(
            encode_word(&instruction, ADDRESS).unwrap(),
            word,
            "{mnemonic}"
        );
        Allegrex::semantics(&instruction, &AnalysisPoint::new(ADDRESS))
            .unwrap_or_else(|error| panic!("{mnemonic} semantic failure: {error}"));
    }
}

#[test]
fn the_public_form_census_matches_the_manual_denominator() {
    let mut actual: Vec<_> = allegrex::VfpuForm::all()
        .map(allegrex::VfpuForm::mnemonic)
        .collect();
    let mut expected: Vec<_> = MANUAL_VFPU_FORMS
        .iter()
        .map(|(mnemonic, _)| *mnemonic)
        .collect();
    actual.sort_unstable();
    expected.sort_unstable();
    assert_eq!(actual, expected);
}
